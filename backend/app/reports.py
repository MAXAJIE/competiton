"""Compartment C3 — report generation + "send test report now" (SKILL.md §7).

The report is generated by the same calc layer (never recomputed) and sent via
Resend's HTTP API. No fake sends: without RESEND_API_KEY configured the call
fails loudly so the button's output is never faked.
"""
from __future__ import annotations

from datetime import date

import httpx

from . import calc, config
from .models import RiskSettings, Transaction


def generate_report(tx: list[Transaction], settings: RiskSettings, today: date | None = None) -> str:
    today = today or date.today()
    bal = calc.get_cash_balance(tx)
    runway = calc.get_runway_months(tx)
    ar = calc.get_ar_ap_summary(tx, today=today)
    lines = [
        "CashMonitoring — daily cash report",
        f"As of {today.isoformat()}",
        "",
        f"Cash balance: {calc.usd(bal)}",
        f"Runway: {('%.1f months' % runway) if runway is not None else 'n/a (no recorded burn yet)'}",
        f"Open AR: {calc.usd(ar['ar'])} (overdue: {calc.usd(ar['arOverdue'])})",
        f"Open AP: {calc.usd(ar['ap'])}",
        "",
        "AR aging: " + ", ".join(f"{k}={calc.usd(v)}" for k, v in ar["arAging"].items()),
        "AP aging: " + ", ".join(f"{k}={calc.usd(v)}" for k, v in ar["apAging"].items()),
    ]
    if settings.enabled and runway is not None and runway < settings.low_cash_threshold_months:
        lines += ["", f"⚠ WARNING: runway ({runway:.1f} months) is below your threshold "
                       f"({settings.low_cash_threshold_months:g} months)."]
    if settings.enabled and ar["ar"] > 0:
        pct = ar["arOverdue"] / ar["ar"] * 100 if ar["ar"] else 0
        if pct >= settings.ar_overdue_spike_pct:
            lines += ["", f"⚠ WARNING: overdue AR is {pct:.0f}% of open AR "
                          f"(your spike threshold: {settings.ar_overdue_spike_pct:g}%)."]
    return "\n".join(lines)


def send_report_email(to: str, subject: str, text: str) -> None:
    if not config.RESEND_API_KEY:
        raise RuntimeError("RESEND_API_KEY not configured; email sending unavailable")
    r = httpx.post(
        "https://api.resend.com/emails",
        headers={"Authorization": f"Bearer {config.RESEND_API_KEY}"},
        json={"from": config.EMAIL_FROM, "to": [to], "subject": subject, "text": text},
        timeout=30,
    )
    r.raise_for_status()
